#!/usr/bin/env bash
# Write or check THIRD_PARTY_NOTICES, the licence texts of the third-party
# software inside the keepgoing executable: the Go runtime and standard
# library, and every module the release targets link.
#   scripts/third-party-notices.sh           rewrite the file
#   scripts/third-party-notices.sh --check   fail when it is out of date
# The module set comes from `go list -deps` for each release target, so a
# module added to go.mod fails the check until its notices are added. Every
# licence, notice and patents file at the root of a module is included; a
# module without a licence file is an error, never an omission.
#
# The Go licence is copied from the toolchain when the file is written. The
# check keeps the committed copy, so two toolchain versions cannot disagree.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/THIRD_PARTY_NOTICES"
targets=${NOTICE_TARGETS:-"darwin/arm64 darwin/amd64 linux/amd64 linux/arm64 windows/amd64 windows/arm64"}
bar="================================================================================"
cd "$root"

modules() {
  go mod download
  for t in $targets; do
    GOOS=${t%/*} GOARCH=${t#*/} CGO_ENABLED=0 go list -deps \
      -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/keepgoing
  done | LC_ALL=C sort -u
}

section() { # heading lines..., then the file to include last
  local file=${*: -1}
  if ! grep -q '[^[:space:]]' "$file" 2>/dev/null; then
    echo "missing or empty licence text: $file" >&2
    return 1
  fi
  echo "$bar"
  printf '%s\n' "${@:1:$#-1}"
  echo "$bar"
  echo
  printf '%s\n' "$(cat "$file")"
  echo
}

# The Go distribution's LICENSE and PATENTS. Some packagings keep them one
# directory above GOROOT.
gofile() {
  local d
  for d in "$(go env GOROOT)" "$(go env GOROOT)/.."; do
    [ -f "$d/$1" ] && { echo "$d/$1"; return; }
  done
  echo "the Go toolchain's $1 file was not found near $(go env GOROOT)" >&2
  return 1
}

# The text of the nth section of the committed file, counted from 1.
committed() {
  awk -v bar="$bar" -v want="$(( $1 * 2 ))" '$0 == bar { n++; next } n == want' "$out" | sed -e '/./,$!d'
}

generate() { # $1, $2: files holding the Go licence and patent grant
  cat <<'INTRO'
Third-party notices for keepgoing

The keepgoing executable contains the third-party software listed below. Each
component remains under its own terms, reproduced here. keepgoing's own terms
are in LICENSE and do not replace them. This file is generated by
scripts/third-party-notices.sh; do not edit it by hand.

INTRO
  section "Go runtime and standard library" \
    "Includes the golang.org/x packages that the Go distribution vendors." "File: LICENSE" "$1"
  section "Go runtime and standard library" "File: PATENTS" "$2"
  local found
  modules | while read -r path version dir; do
    found=0
    for f in $(cd "$dir" && ls | LC_ALL=C sort | grep -iE '^(licen[cs]e|copying|notice|patents)([.-].*)?$' || true); do
      section "Module: $path $version" "File: $f" "$dir/$f"
      case "$f" in [Ll][Ii][Cc]*|[Cc][Oo][Pp]*) found=1 ;; esac
    done
    if [ "$found" = 0 ]; then
      echo "no licence file found for module $path $version" >&2
      exit 1
    fi
  done
}

case "${1:-}" in
  "")
    license=$(gofile LICENSE); patents=$(gofile PATENTS)
    generate "$license" "$patents" > "$out.tmp"
    mv "$out.tmp" "$out"
    ;;
  --check)
    [ -f "$out" ] || { echo "THIRD_PARTY_NOTICES is missing; run scripts/third-party-notices.sh" >&2; exit 1; }
    work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
    # The committed Go texts stand in for the toolchain's.
    committed 1 > "$work/go-license"; committed 2 > "$work/go-patents"
    generate "$work/go-license" "$work/go-patents" > "$work/expected" || {
      echo "THIRD_PARTY_NOTICES has no Go licence or patents text, or a module has no licence" >&2; exit 1; }
    if ! diff -u "$out" "$work/expected" > "$work/diff"; then
      echo "THIRD_PARTY_NOTICES does not match the modules in the executable." >&2
      echo "Run scripts/third-party-notices.sh, review the result and commit it." >&2
      head -40 "$work/diff" >&2
      exit 1
    fi
    ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
